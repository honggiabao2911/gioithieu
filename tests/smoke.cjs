const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const base = process.env.BASE_URL || 'http://127.0.0.1:8000';
(async () => {
 const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
 const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
 const errors = []; page.on('pageerror', e => errors.push(e.message));
 await page.goto(base, { waitUntil: 'networkidle' });
 assert.equal(await page.locator('.constructing').count(), 0, 'content is never gated by a scroll timeline');
 const links = await page.locator('.project-card').evaluateAll(es => es.map(e => e.href));
 assert.equal(new Set(links).size, 4);
 assert.ok(links.includes('https://dsalhdsakj.github.io/chucmung/'));
 const height = await page.locator('main').evaluate(e => e.offsetHeight);
 await page.locator('#swarm-controls summary').click();
 await page.locator('#effects-toggle').click();
 assert.equal(await page.locator('.swarm-layer').getAttribute('hidden'), '');
 assert.equal(await page.locator('main').evaluate(e => e.offsetHeight), height);
 await page.reload();
 assert.equal(await page.locator('#effects-toggle').getAttribute('aria-pressed'), 'false');
 await page.locator('#swarm-controls summary').click();
 await page.locator('#effects-toggle').click();
 await page.locator('#activity').selectOption('lively');
 assert.equal(await page.locator('.living-cursor').count(), 12);
 await page.goto(base + '/#projects');
 assert.ok(await page.locator('#projects h2').isVisible());
 assert.equal(await page.locator('.constructing').count(), 0);
 for (const width of [320,375,390,768,1024,1440]) {
   await page.setViewportSize({ width, height: 844 }); await page.waitForTimeout(100);
   assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `overflow at ${width}`);
 }
 await page.locator('#chat-launcher').click();
 await page.locator('#chat-close').focus(); await page.keyboard.press('Escape');
 assert.ok(await page.locator('#chat-panel').isHidden());
 assert.equal(await page.locator('#chat-launcher').evaluate(e => e === document.activeElement), true);
 const quiet = await browser.newContext({ reducedMotion: 'reduce' }); const p2 = await quiet.newPage();
 await p2.goto(base); assert.equal(await p2.locator('.swarm-layer').getAttribute('hidden'), '');
 assert.equal(await p2.locator('.constructing').count(), 0);
 const nojs = await browser.newContext({ javaScriptEnabled: false }); const p3 = await nojs.newPage();
 await p3.goto(base); assert.ok(await p3.locator('h1').isVisible()); assert.ok(await p3.locator('#swarm-controls').isHidden());
 assert.deepEqual(errors, []); await browser.close();
 console.log('PASS: always-complete content, 4 unique projects, effect preferences, density, 6 viewport widths, deep link, keyboard/Escape, reduced motion, no-JS.');
})().catch(e => { console.error(e); process.exit(1); });
