const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const base = process.env.BASE_URL || 'http://127.0.0.1:8000';
(async () => {
 const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
 const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
 const errors = []; page.on('pageerror', e => errors.push(e.message));
 await page.goto(base, { waitUntil: 'networkidle' });
 await page.locator('#chat-launcher').click();
 assert.match(await page.locator('#chat-mode').innerText(), /Giới thiệu tự động/);
 await page.locator('[data-question="Gia Bảo đang học gì?"]').click();
 assert.match(await page.locator('.chat-message').last().innerText(), /An ninh mạng tại iSPACE/);
 await page.locator('.chat-action').last().click();
 assert.ok(await page.locator('#chat-panel').isHidden());
 await page.waitForTimeout(250);
 assert.ok(await page.locator('.living-cursor[data-state="guide"]').count() > 0);
 await page.locator('#chat-launcher').click();
 await page.locator('#chat-clear').click();
 assert.equal(await page.locator('.chat-message').count(), 1);
 await page.locator('#chat-input').fill('<img src=x onerror=alert(1)>');
 await page.locator('#chat-send').click();
 assert.equal(await page.locator('.chat-message img').count(), 0);
 assert.match(await page.locator('.chat-message').last().innerText(), /chưa có dữ liệu/);
 await page.locator('#chat-input').fill('Gửi liên tục'); await page.locator('#chat-send').click();
 assert.match(await page.locator('#chat-status').innerText(), /Chờ một nhịp/);
 assert.equal(await page.locator('.chat-message.user').count(), 1);
 await page.reload(); await page.locator('#chat-launcher').click();
 assert.equal(await page.locator('.chat-message.user').count(), 1, 'session history restores');
 assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
 const configured = async (status, body) => {
   const p = await browser.newPage(); p.on('pageerror', e => errors.push(e.message));
   await p.route('**/config.js*', route => route.fulfill({ contentType: 'application/javascript', body: 'window.PORTFOLIO_CHAT_CONFIG={endpoint:"https://chat.test/"};' }));
   await p.route('https://chat.test/**', route => route.fulfill({ status: route.request().method() === 'OPTIONS' ? 204 : status, headers: { 'Access-Control-Allow-Origin': '*', 'Access-Control-Allow-Methods': 'POST, OPTIONS', 'Access-Control-Allow-Headers': 'Content-Type', 'Content-Type': 'application/json' }, body: route.request().method() === 'OPTIONS' ? '' : JSON.stringify(body) }));
   await p.goto(base); await p.locator('#chat-launcher').click();
   await p.locator('[data-question="Xem các dự án"]').click();
   await p.waitForFunction(() => document.getElementById('chat-send').disabled === false);
   return p;
 };
 const failed = await configured(429, { error: 'too_many_requests' });
 assert.match(await failed.locator('#chat-mode').innerText(), /Giới thiệu tự động/);
 assert.match(await failed.locator('.chat-message').last().innerText(), /bốn dự án/);
 assert.match(await failed.locator('#chat-status').innerText(), /giới hạn/);
 const remote = await configured(200, { reply: '<img src=x onerror="alert(1)"> Chào bạn.', action: 'javascript:alert(1)' });
 assert.match(await remote.locator('#chat-mode').innerText(), /Đã kết nối/);
 assert.equal(await remote.locator('.chat-message img').count(), 0);
 assert.equal(await remote.locator('.chat-action').count(), 0);
 assert.match(await remote.locator('.chat-message').last().innerText(), /<img/);
 assert.deepEqual(errors, []); await browser.close();
 console.log('PASS: local facts, action/guide, clear/session restore, XSS-safe text, anti-spam, mobile chat, mocked endpoint success/error and action allowlist.');
})().catch(e => { console.error(e); process.exit(1); });
