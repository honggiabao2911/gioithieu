const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const base = process.env.BASE_URL || 'http://127.0.0.1:8000';
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base, { waitUntil: 'networkidle' });
  assert.equal(await page.locator('.ambient-background').getAttribute('hidden'), null);
  assert.equal(await page.locator('.ambient-background canvas').count(), 1);
  await page.mouse.move(700, 300);
  await page.waitForTimeout(100);
  assert.equal(await page.locator('.pointer-halo').evaluate(el => el.classList.contains('is-visible')), true);
  // Deep linking finishes construction so hover targets are fully usable.
  await page.goto(base + '/#projects');
  const art = page.locator('.project-art').first();
  await art.hover({ position: { x: 45, y: 60 } });
  assert.notEqual(await art.evaluate(el => el.style.getPropertyValue('--tilt-y')), '');
  await page.mouse.move(10, 10);
  await page.waitForTimeout(350);
  assert.equal(await art.evaluate(el => el.style.getPropertyValue('--tilt-y')), '0deg');
  await page.locator('#effects-toggle').click();
  assert.equal(await page.locator('.ambient-background').getAttribute('hidden'), '');
  await art.hover();
  assert.equal(await art.evaluate(el => getComputedStyle(el).transform), 'none');
  await page.locator('#replay').click();
  await page.waitForTimeout(100);
  assert.equal(await page.locator('.ambient-background').getAttribute('hidden'), null);
  await page.waitForTimeout(850);
  assert.equal(await page.locator('.interaction-spark').count(), 0);
  const reduced = await browser.newContext({ reducedMotion: 'reduce', viewport: { width: 390, height: 844 } });
  const quiet = await reduced.newPage();
  await quiet.goto(base);
  assert.equal(await quiet.locator('.ambient-background').getAttribute('hidden'), '');
  assert.equal(await quiet.locator('.constructing').count(), 0);
  assert.ok(await quiet.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: particle canvas, pointer halo, card tilt/reset, global effects-off, replay, spark cleanup, reduced motion.');
})().catch(error => { console.error(error); process.exit(1); });
